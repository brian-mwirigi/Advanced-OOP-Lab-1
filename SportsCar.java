public class SportsCar extends Vehicle implements Automobile {

    public void accelerate() {
        System.out.println("sports car increasing speed");
    }
    public void stop() {
        System.out.println("sports car stopped");
    }
    public void gas() {
        System.out.println("expensive gas only for the sports car");
    }
    public void startCar() {
        System.out.println("sports car is started");
    }
    public void turnOffCar() {
        System.out.println("sports car is turned off");
    }
}
